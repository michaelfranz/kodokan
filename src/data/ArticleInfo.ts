const options: Fuse.FuseOptions = {
    distance: 100,
    keys: ['name', 'search', 'synonym', 'translation'],
    location: 0,
    maxPatternLength: 48,
    minMatchCharLength: 1,
    shouldSort: true,
    threshold: 0.15,
}

export default class ArticleInfo {
    public static allArticles(): Article[] {
        return articleList
    }

    public static articleCount(): number {
        return articleList.length
    }

    public static articlesMatchingSearchTerm(searchTerm: string): Article[] {
        const fuse = new Fuse(articleList, options)
        return fuse.search(searchTerm)
    }

    public static articlesForTerms(terms: string[]) {
        return terms.map(term => articleDictionary.get(term))
    }

    public static articleForTerm(term: string) {
        return articleDictionary.get(term)
    }
}
